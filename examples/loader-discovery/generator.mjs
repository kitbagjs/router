import { mkdir, readFile, readdir, rename, rm, writeFile } from 'node:fs/promises'
import { dirname, isAbsolute, relative, resolve } from 'node:path'
import { parse } from '@vue/compiler-sfc'
import { IndentationText, Node, Project, QuoteKind, SyntaxKind, VariableDeclarationKind } from 'ts-morph'

export const MACROS = 'virtual:kitbag-loader-macros'
export const normalize = path => path.replaceAll('\\', '/')
const header = '// Generated by Kitbag loader discovery. Do not edit.\n'

function fail(file, message) {
  throw new Error(`[kitbag-loader-discovery] ${file}: ${message}`)
}

function sourceFile(code, file) {
  return new Project({ useInMemoryFileSystem: true, manipulationSettings: { indentationText: IndentationText.TwoSpaces, quoteKind: QuoteKind.Single } }).createSourceFile(file, code)
}

function macroBindings(source) {
  return source.getImportDeclarations().filter(node => node.getModuleSpecifierValue() === MACROS)
    .flatMap(node => node.getNamedImports().filter(binding => binding.getName() === 'defineLoader')
      .map(binding => binding.getAliasNode()?.getText() ?? binding.getName()))
}

export function parseComponent(code, file) {
  const { descriptor, errors } = parse(code, { filename: file })
  if (errors.length) fail(file, String(errors[0]))
  const source = sourceFile(descriptor.script?.content ?? '', file + '.ts')
  const bindings = macroBindings(source)
  const setup = sourceFile(descriptor.scriptSetup?.content ?? '', file + '.setup.ts')
  if (macroBindings(setup).length) fail(file, 'defineLoader belongs in the normal <script>, not <script setup>.')
  const loaders = []
  if (bindings.length) {
    if (!descriptor.scriptSetup) fail(file, 'Loader declarations require a <script setup> consumer.')
    if (descriptor.script.src || descriptor.scriptSetup.src) fail(file, 'External script blocks are not supported.')
    for (const statement of source.getStatements()) {
      if (Node.isImportDeclaration(statement)) continue
      const declarations = Node.isVariableStatement(statement) ? statement.getDeclarations() : []
      const declaration = declarations[0]
      const call = declaration?.getInitializer()
      if (!declaration || declarations.length !== 1 || !statement.isExported()
        || statement.getDeclarationKind() !== VariableDeclarationKind.Const
        || !Node.isIdentifier(declaration.getNameNode()) || !Node.isCallExpression(call)
        || !Node.isIdentifier(call.getExpression()) || !bindings.includes(call.getExpression().getText())) {
        fail(file, 'The loader script may contain imports and exported const defineLoader(...) declarations only.')
      }
      const args = call.getArguments()
      const callback = args[0]
      if (args.length > 2 || !(Node.isArrowFunction(callback) || Node.isFunctionExpression(callback)) || callback.getParameters().length) {
        fail(file, 'This proof of concept requires an inline loader callback with no parameters.')
      }
      const name = declaration.getName()
      if (name.startsWith('__')) fail(file, 'Loader export names starting with __ are reserved.')
      if (setup.getDescendantsOfKind(SyntaxKind.VariableDeclaration).some(node => node.getName() === name)) {
        fail(file, `Setup already declares ${name}. Await the exported loader under a different name.`)
      }
      loaders.push({ file, name, key: name, callback: callback.getText(), options: args[1]?.getText() ?? '{}' })
    }
  }
  return { descriptor, source, loaders }
}

function moduleSpecifier(from, to) {
  let path = normalize(relative(dirname(from), to)).replace(/\.ts$/, '')
  if (!path.startsWith('.')) path = './' + path
  return path
}

function relocateImports(source, from, to) {
  const relocate = value => value.startsWith('.') ? moduleSpecifier(to, resolve(dirname(from), value)) : value
  for (const node of source.getImportDeclarations()) node.setModuleSpecifier(relocate(node.getModuleSpecifierValue()))
  for (const node of source.getExportDeclarations()) {
    const value = node.getModuleSpecifierValue()
    if (value) node.setModuleSpecifier(relocate(value))
  }
  for (const call of source.getDescendantsOfKind(SyntaxKind.CallExpression)) {
    if (call.getExpression().getKind() !== SyntaxKind.ImportKeyword) continue
    const argument = call.getArguments()[0]
    if (Node.isStringLiteral(argument)) argument.setLiteralValue(relocate(argument.getLiteralValue()))
  }
}

function componentTags(descriptor) {
  const tags = new Set()
  function visit(node) {
    if (node.type === 1) {
      if (node.tag === 'component') fail(descriptor.filename, 'Dynamic <component> discovery is not supported; use statically imported components.')
      tags.add(node.tag.replaceAll('-', '').toLowerCase())
    }
    for (const child of node.children ?? []) visit(child)
  }
  if (descriptor.template?.ast) visit(descriptor.template.ast)
  return tags
}

function routeChain(expression, names) {
  const calls = []
  while (Node.isCallExpression(expression) && Node.isPropertyAccessExpression(expression.getExpression())) {
    const property = expression.getExpression()
    calls.unshift({ call: expression, method: property.getName() })
    expression = property.getExpression()
  }
  if (!Node.isCallExpression(expression) || !Node.isIdentifier(expression.getExpression()) || !names.includes(expression.getExpression().getText())) return
  return { calls, create: expression }
}

async function saveIfChanged(file, contents) {
  try { if (await readFile(file, 'utf8') === contents) return } catch (error) { if (error.code !== 'ENOENT') throw error }
  await mkdir(dirname(file), { recursive: true })
  await writeFile(file + '.tmp', contents)
  await rename(file + '.tmp', file)
}

async function removeStaleLoaders(directory, expected) {
  for (const entry of await readdir(directory, { withFileTypes: true }).catch(error => {
    if (error.code === 'ENOENT') return []
    throw error
  })) {
    const file = resolve(directory, entry.name)
    if (entry.isDirectory()) await removeStaleLoaders(file, expected)
    else if (file.endsWith('.ts') && !expected.has(file) && (await readFile(file, 'utf8')).startsWith(header)) await rm(file)
  }
}

/** Standalone, persistent code generation; Vite is only one caller. */
export function createGenerator({ root, routeFiles, outputDir = '.kitbag' }) {
  root = normalize(resolve(root))
  const output = normalize(resolve(root, outputDir))
  const loaderFile = file => normalize(resolve(output, 'loaders', relative(root, file).replace(/\.vue$/, '.ts')))
  const routeFile = file => normalize(resolve(output, relative(root, file).replace(/\.ts$/, '.generated.ts')))

  async function generate({ resolveId, watchFile = () => {} } = {}) {
    const watched = new Set()
    const components = new Map()
    const emitted = new Map()
    const manifests = []
    async function find(specifier, importer) {
      const id = resolveId ? await resolveId(specifier, importer)
        : (specifier.startsWith('.') || isAbsolute(specifier)) && resolve(dirname(importer), specifier)
      if (!id) fail(importer, `Cannot resolve ${specifier}. The standalone generator supports relative SFC imports.`)
      return normalize(id.split('?')[0])
    }
    async function collect(file, seen = new Set()) {
      if (seen.has(file)) return []
      seen.add(file)
      watched.add(file)
      watchFile(file)
      let component = components.get(file)
      if (!component) {
        component = parseComponent(await readFile(file, 'utf8'), file)
        components.set(file, component)
      }
      const result = [...component.loaders]
      const tags = componentTags(component.descriptor)
      for (const script of [component.descriptor.script, component.descriptor.scriptSetup].filter(Boolean)) {
        for (const node of sourceFile(script.content, file + '.imports.ts').getImportDeclarations()) {
          const binding = node.getDefaultImport()?.getText()
          if (!binding || node.isTypeOnly() || !node.getModuleSpecifierValue().endsWith('.vue')) continue
          if (tags.has(binding.replaceAll('-', '').toLowerCase())) result.push(...await collect(await find(node.getModuleSpecifierValue(), file), seen))
        }
      }
      return result
    }

    for (const configuredFile of routeFiles) {
      const file = normalize(resolve(root, configuredFile))
      watched.add(file)
      watchFile(file)
      const source = sourceFile(await readFile(file, 'utf8'), file)
      const generatedFile = routeFile(file)
      const names = source.getImportDeclarations().filter(node => node.getModuleSpecifierValue() === '@kitbag/router')
        .flatMap(node => node.getNamedImports().filter(binding => binding.getName() === 'createRoute')
          .map(binding => binding.getAliasNode()?.getText() ?? binding.getName()))
      const vueImports = new Map(source.getImportDeclarations().filter(node => node.getDefaultImport() && node.getModuleSpecifierValue().endsWith('.vue'))
        .map(node => [node.getDefaultImport().getText(), node.getModuleSpecifierValue()]))
      const routeLoaders = new Map()
      const entries = []
      let index = 0
      for (const statement of source.getVariableStatements()) {
        for (const declaration of statement.getDeclarations()) {
          const initializer = declaration.getInitializer()
          if (!initializer) continue
          const chain = routeChain(initializer, names)
          if (!chain) continue
          const options = chain.create.getArguments()[0]
          if (!Node.isObjectLiteralExpression(options) || options.getProperties().some(Node.isSpreadAssignment)) fail(file, 'Route options must be an inline object without spreads in this proof of concept.')
          const property = options.getProperty('parent')
          const parent = Node.isShorthandPropertyAssignment(property) ? property.getNameNode() : property?.getInitializer?.()
          if (parent && (!Node.isIdentifier(parent) || !routeLoaders.has(parent.getText()))) fail(file, 'A parent route must be an earlier createRoute declaration in the same module.')
          const inherited = new Map(parent ? routeLoaders.get(parent.getText()) : [])
          const found = new Map()
          const manualNames = new Set()
          for (const { call, method } of chain.calls) {
            if (method === 'addLoader') {
              const option = call.getArguments()[1]
              if (option && !Node.isObjectLiteralExpression(option)) fail(file, 'Manual loader options must be an inline object in this proof of concept.')
              const name = option?.getProperty('name')?.getInitializer?.()
              if (name && !Node.isStringLiteral(name)) fail(file, 'Manual loader names must be string literals in this proof of concept.')
              manualNames.add(name ? name.getLiteralValue() : 'default')
            }
            if (method !== 'addView') continue
            const view = call.getArguments()[0]
            let specifier = Node.isIdentifier(view) && vueImports.get(view.getText())
            if (!specifier && view) {
              const dynamic = [view, ...view.getDescendants()].filter(node => Node.isCallExpression(node) && node.getExpression().getKind() === SyntaxKind.ImportKeyword)
              const argument = dynamic.length === 1 ? dynamic[0].getArguments()[0] : undefined
              if (Node.isStringLiteral(argument) && argument.getLiteralValue().endsWith('.vue')) specifier = argument.getLiteralValue()
            }
            if (!specifier) fail(file, `Cannot discover the view for ${declaration.getName()}; use an imported SFC or an inline lazy SFC import.`)
            for (const loader of await collect(await find(specifier, file))) {
              const existing = found.get(loader.key) ?? inherited.get(loader.key)
              if ((existing && existing.file !== loader.file) || manualNames.has(loader.key)) fail(file, `Loader name ${loader.key} conflicts. Use distinct loader export names within a route and its ancestors.`)
              found.set(loader.key, loader)
            }
          }
          let suffix = ''
          for (const loader of found.values()) {
            if (manualNames.has(loader.key)) fail(file, `Loader name ${loader.key} conflicts with a manual loader.`)
            if (inherited.has(loader.key)) continue
            const alias = `__kitbag_load_${index++}`
            source.addImportDeclaration({ moduleSpecifier: moduleSpecifier(file, loaderFile(loader.file)), namedImports: [
              { name: loader.name, alias }, { name: `__options_${loader.name}`, alias: alias + '_options' },
            ] })
            suffix += `\n.addLoader(${alias}, { ...${alias}_options, name: '${loader.key}' })`
          }
          routeLoaders.set(declaration.getName(), new Map([...inherited, ...found,
            ...[...manualNames].map(key => [key, { file: `manual:${declaration.getName()}`, name: key, key }]),
          ]))
          if (suffix) declaration.setInitializer(initializer.getText() + suffix)
          entries.push({ route: declaration.getName(), loaders: [...found.values()].map(({ file, name, key }) => ({ component: normalize(relative(root, file)), export: name, key })) })
        }
      }
      relocateImports(source, file, generatedFile)
      source.formatText({ indentSize: 2, semicolons: 'remove' })
      const generated = header + source.getFullText()
      emitted.set(generatedFile, generated)
      manifests.push({ file: normalize(relative(root, file)), output: normalize(relative(root, generatedFile)), routes: entries, generated })
    }

    const loaderFiles = new Set()
    for (const [file, component] of components) {
      if (!component.loaders.length) continue
      if (relative(root, file).startsWith('..')) fail(file, 'Discovered loader components must be inside the configured root.')
      const target = loaderFile(file)
      const source = sourceFile(component.descriptor.script.content, file + '.loader.ts')
      for (const node of source.getImportDeclarations()) if (node.getModuleSpecifierValue() === MACROS) node.remove()
      for (const loader of component.loaders) {
        source.getVariableDeclarationOrThrow(loader.name).setInitializer(loader.callback)
        source.addVariableStatement({ isExported: true, declarationKind: VariableDeclarationKind.Const, declarations: [
          { name: `__options_${loader.name}`, initializer: `(${loader.options}) satisfies import('@kitbag/router').AddLoaderOptions` },
        ] })
      }
      relocateImports(source, file, target)
      source.formatText({ indentSize: 2, semicolons: 'remove' })
      emitted.set(target, header + source.getFullText())
      loaderFiles.add(target)
    }
    for (const [file, contents] of emitted) if (loaderFiles.has(file)) await saveIfChanged(file, contents)
    for (const [file, contents] of emitted) if (!loaderFiles.has(file)) await saveIfChanged(file, contents)
    await saveIfChanged(resolve(output, 'manifest.generated.ts'), header + `export default ${JSON.stringify(manifests, null, 2)} as const\n`)
    await removeStaleLoaders(resolve(output, 'loaders'), loaderFiles)
    return { watched, manifests }
  }
  return { generate, loaderFile, routeFile, output }
}
