import { dirname, relative } from 'node:path'
import MagicString from 'magic-string'
import { Node, Project, SyntaxKind } from 'ts-morph'
import type { ContextReferences, Diagnostic, RouteDiscovery, ReusableDefinition, ResolveImportPath, ParsedModule } from './types'
import { resolveRelativeImportPath } from './readModule'
import { unwrapExpression } from './syntax'
import { createImportPlan, type ImportRequest, type ExistingImport } from './planImports'
import { planRouteGeneration, type GenerationPlan } from './planRouteGeneration'

export const GENERATED_HEADER = '// Generated by @kitbag/router/vite. Changes will be overwritten.\n'

export function getGeneratedModulePath(file: string): string {
  return file.replace(/\.[cm]?[jt]sx?$/, '.generated.ts')
}

export function getRelativeImportSpecifier(from: string, to: string): string {
  const path = relative(dirname(from), to).replaceAll('\\', '/')
    .replace(/\.[cm]?[jt]sx?$/, '')
  return path.startsWith('.') ? path : `./${path}`
}

export type GeneratedModules = {
  files: Map<string, string>,
  diagnostics: Diagnostic[],
}

export async function generateRouteModules(discovery: RouteDiscovery, resolveImportPath: ResolveImportPath = resolveRelativeImportPath): Promise<GeneratedModules> {
  const files = new Map<string, string>()
  const plan = await planRouteGeneration(discovery, resolveImportPath)

  for (const file of plan.modulePaths) {
    const routeModule = discovery.parsedModules.get(file)

    if (!routeModule) {
      throw new Error(`Missing route source: ${file}`)
    }

    const contents = await generateRouteModule(discovery, plan, routeModule, resolveImportPath)
    files.set(getGeneratedModulePath(file), contents)
  }

  return { files, diagnostics: plan.diagnostics }
}

async function generateRouteModule(discovery: RouteDiscovery, plan: GenerationPlan, routeModule: ParsedModule, resolveImportPath: ResolveImportPath): Promise<string> {
  const { loaderAdditions, contextExportNames, modulePaths } = plan
  const file = routeModule.file

  const generatedFilePath = getGeneratedModulePath(file)
  const generatedSource = new MagicString(routeModule.sourceText)
  const routeDeclarations = new Set([...discovery.routeDefinitions.values()].filter((route) => route.routeModule === routeModule).map((route) => route.routeDeclaration))
  const routeExportNames = new Set(discovery.routeExports.filter((entry) => entry.file === file).map((entry) => entry.name))
  const importPlan = await planModuleImports(discovery, plan, routeModule, resolveImportPath)
  augmentRouteDefinitions()
  await redirectImportsToGeneratedModules()
  reuseSharedDefinitions()

  return removeUnusedImports(generatedFilePath, GENERATED_HEADER + importPlan.declarations.join('\n') + '\n' + generatedSource.toString())

  function getImportedReference(name: string, importedModulePath: string): string {
    return importPlan.getImportReference(name, getRelativeImportSpecifier(generatedFilePath, importedModulePath))
  }

  function renderContextReferences(expression: string, references: ContextReferences): string {
    if (!references.routes.length) {
      return expression
    }

    const replacements = new Map(references.routes.map(({ index, route }) => {
      const name = contextExportNames.get(route)

      if (!name) {
        throw new Error(`Missing generated context export for ${route.id}`)
      }

      if (route.routeModule !== routeModule) {
        return [index, getImportedReference(name, getGeneratedModulePath(route.routeModule.file))]
      }

      const localRouteName = Node.isVariableDeclaration(route.routeDeclaration) ? route.routeDeclaration.getName() : name
      return [index, localRouteName]
    }))
    return `[${Array.from({ length: references.length }, (_, index) => replacements.get(index) ?? `(${expression})[${index}]`).join(', ')}]`
  }

  function renderReusableDefinition(reusableDefinition: ReusableDefinition): string {
    const reference = getImportedReference(reusableDefinition.name, reusableDefinition.file)
    const contexts = discovery.definitionContexts.get(reusableDefinition.id)

    if (!contexts?.routes.length) {
      return reference
    }

    return `{ ...${reference}, context: ${renderContextReferences(`${reference}.context`, contexts)} }`
  }

  function augmentRouteDefinitions(): void {
    for (const route of discovery.routeDefinitions.values()) {
      if (route.routeModule !== routeModule) {
        continue
      }

      const contextName = contextExportNames.get(route)

      if (contextName) {
        if (Node.isVariableDeclaration(route.routeDeclaration)) {
          generatedSource.append(`\nexport { ${route.routeDeclaration.getName()} as ${contextName} }\n`)
        } else {
          generatedSource.overwrite(route.routeDeclaration.getStart(), route.routeDeclaration.getExpression().getStart(), `export const ${contextName} = `)
          generatedSource.append(`\nexport default ${contextName}\n`)
        }
      }

      if (route.context?.references.routes.length) {
        const { expression, references } = route.context
        generatedSource.overwrite(expression.getStart(), expression.getEnd(), renderContextReferences(expression.getText(), references))
      }

      for (const attachment of route.reusableContextAttachments) {
        const contexts = discovery.definitionContexts.get(attachment.definition.id)

        if (contexts?.routes.length) {
          generatedSource.overwrite(attachment.argument.getStart(), attachment.argument.getEnd(), renderReusableDefinition(attachment.definition))
        }
      }

      for (const attachment of route.explicitLoaders) {
        const contexts = attachment.loader ? discovery.definitionContexts.get(attachment.loader.id) : undefined

        if (attachment.loader && contexts?.routes.length) {
          generatedSource.overwrite(attachment.argument.getStart(), attachment.argument.getEnd(), renderReusableDefinition(attachment.loader))
        }
      }

      const routeInitializer = Node.isVariableDeclaration(route.routeDeclaration) ? route.routeDeclaration.getInitializerOrThrow() : route.routeDeclaration.getExpression()
      const routeLoaders = loaderAdditions.get(route) ?? []
      const loaderCalls = routeLoaders.map(({ loader, name }) => {
        if (!loader) {
          throw new Error('Generated attachment requires a loader definition')
        }

        return `\n  .addLoader(${renderReusableDefinition(loader)}, { name: ${JSON.stringify(name)} })`
      })
      generatedSource.appendLeft(unwrapExpression(routeInitializer).getEnd(), loaderCalls.join(''))
    }
  }

  async function redirectImportsToGeneratedModules(): Promise<void> {
    for (const declaration of [...routeModule.syntaxTree.getImportDeclarations(), ...routeModule.syntaxTree.getExportDeclarations()]) {
      const specifier = declaration.getModuleSpecifierValue()
      const node = declaration.getModuleSpecifier()
      const referencedModulePath = specifier ? await resolveImportPath(specifier, file) : undefined

      if (node && referencedModulePath && modulePaths.has(referencedModulePath) && !declaration.isTypeOnly()) {
        generatedSource.overwrite(node.getStart(), node.getEnd(), JSON.stringify(getRelativeImportSpecifier(generatedFilePath, getGeneratedModulePath(referencedModulePath))))
      }
    }
  }

  function reuseSharedDefinitions(): void {
    const reusesSource = routeModule.syntaxTree.getVariableDeclarations().some((declaration) => declaration.isExported() && !routeDeclarations.has(declaration) && !routeExportNames.has(declaration.getName()))

    // Non-route exported values may carry loader/param identity. Read them from the authored module.
    for (const declaration of routeModule.syntaxTree.getVariableDeclarations()) {
      if (routeDeclarations.has(declaration) || routeExportNames.has(declaration.getName())) {
        continue
      }

      const definitionInitializer = declaration.getInitializer()

      if (!definitionInitializer) {
        continue
      }

      if (declaration.isExported()) {
        generatedSource.overwrite(definitionInitializer.getStart(), definitionInitializer.getEnd(), getImportedReference(declaration.getName(), file))
      } else if (reusesSource && (definitionInitializer.getDescendantsOfKind(SyntaxKind.CallExpression).length || Node.isCallExpression(definitionInitializer))) {
        throw new Error(`Move or export the module-scope definition ${declaration.getName()} in ${file} before generating routes. Its identity cannot safely be copied.`)
      }
    }
  }
}

function removeUnusedImports(file: string, generatedSource: string): string {
  const project = new Project({ useInMemoryFileSystem: true })
  const parsedModule = project.createSourceFile(file, generatedSource)

  function hasReferencesOutsideImports(node: Node): boolean {
    return !Node.isIdentifier(node) || node.findReferencesAsNodes().some((reference) => !reference.getFirstAncestorByKind(SyntaxKind.ImportDeclaration))
  }

  for (const declaration of parsedModule.getImportDeclarations()) {
    if (!declaration.getImportClause()) {
      continue
    }

    const defaultImport = declaration.getDefaultImport()
    const namespace = declaration.getNamespaceImport()

    if (defaultImport && !hasReferencesOutsideImports(defaultImport)) {
      declaration.removeDefaultImport()
    }

    if (declaration.wasForgotten()) {
      continue
    }

    if (namespace && !hasReferencesOutsideImports(namespace)) {
      declaration.removeNamespaceImport()
    }

    if (declaration.wasForgotten()) {
      continue
    }

    for (const specifier of declaration.getNamedImports()) {
      if (!hasReferencesOutsideImports(specifier.getAliasNode() ?? specifier.getNameNode())) {
        specifier.remove()
      }
    }

    if (!declaration.wasForgotten() && !declaration.getDefaultImport() && !declaration.getNamespaceImport() && !declaration.getNamedImports().length) {
      declaration.remove()
    }
  }

  return parsedModule.getFullText()
}

async function planModuleImports(discovery: RouteDiscovery, plan: GenerationPlan, routeModule: ParsedModule, resolveImportPath: ResolveImportPath): Promise<ReturnType<typeof createImportPlan>> {
  const { loaderAdditions, contextExportNames, modulePaths } = plan
  const file = routeModule.file
  const generatedFilePath = getGeneratedModulePath(file)
  const routeDeclarations = new Set([...discovery.routeDefinitions.values()].filter((route) => route.routeModule === routeModule).map((route) => route.routeDeclaration))
  const routeExportNames = new Set(discovery.routeExports.filter((entry) => entry.file === file).map((entry) => entry.name))
  const requiredImports: ImportRequest[] = []
  const existingImports: ExistingImport[] = []
  const reservedNames = routeModule.syntaxTree.getDescendantsOfKind(SyntaxKind.Identifier).map((node) => node.getText())

  function requireImport(exportName: string, importedModulePath: string): void {
    requiredImports.push({ exportName, moduleSpecifier: getRelativeImportSpecifier(generatedFilePath, importedModulePath) })
  }

  for (const route of discovery.routeDefinitions.values()) {
    if (route.routeModule !== routeModule) {
      continue
    }

    const definitions = [
      ...(loaderAdditions.get(route) ?? []).flatMap((entry) => {
        return entry.loader ? [entry.loader] : []
      }),
      ...route.explicitLoaders.flatMap((entry) => {
        return entry.loader && discovery.definitionContexts.get(entry.loader.id)?.routes.length ? [entry.loader] : []
      }),
      ...route.reusableContextAttachments.filter((entry) => discovery.definitionContexts.get(entry.definition.id)?.routes.length).map((entry) => entry.definition),
    ]
    const contexts = [...route.context?.references.routes ?? []]

    for (const definition of definitions) {
      requireImport(definition.name, definition.file)
      contexts.push(...discovery.definitionContexts.get(definition.id)?.routes ?? [])
    }

    for (const { route: contextRoute } of contexts) {
      if (contextRoute.routeModule !== routeModule) {
        const name = contextExportNames.get(contextRoute)

        if (!name) {
          throw new Error(`Missing generated context export for ${contextRoute.id}`)
        }

        requireImport(name, getGeneratedModulePath(contextRoute.routeModule.file))
      }
    }
  }

  for (const declaration of routeModule.syntaxTree.getVariableDeclarations()) {
    if (declaration.isExported() && declaration.getInitializer() && !routeDeclarations.has(declaration) && !routeExportNames.has(declaration.getName())) {
      requireImport(declaration.getName(), file)
    }
  }

  for (const declaration of routeModule.syntaxTree.getImportDeclarations()) {
    if (declaration.isTypeOnly()) {
      continue
    }

    const referencedModulePath = await resolveImportPath(declaration.getModuleSpecifierValue(), file)

    if (!referencedModulePath) {
      continue
    }

    const importSpecifier = getRelativeImportSpecifier(generatedFilePath, modulePaths.has(referencedModulePath) ? getGeneratedModulePath(referencedModulePath) : referencedModulePath)
    const defaultImport = declaration.getDefaultImport()

    if (defaultImport) {
      existingImports.push({ exportName: 'default', moduleSpecifier: importSpecifier, localName: defaultImport.getText() })
    }

    for (const specifier of declaration.getNamedImports()) {
      if (!specifier.isTypeOnly()) {
        existingImports.push({ exportName: specifier.getName(), moduleSpecifier: importSpecifier, localName: specifier.getAliasNode()?.getText() ?? specifier.getName() })
      }
    }
  }

  return createImportPlan(requiredImports, reservedNames, existingImports)
}
